// Draws the micro flags and writes app/flags.css (docs/adr/0020 §8, docs/adr/0021 §3).
//   node scripts/build-flags.mjs            write app/flags.css
//   node scripts/build-flags.mjs --check    exit 1 when app/flags.css is not what this file draws (the audit runs this)
//
// Why a stylesheet and not an inline <svg> per flag: the language menu, the gate and the footer carry about 25 flags, and each inline SVG
// was 3 to 7 DOM nodes that the browser had to build, style and lay out again every time a web font swapped in (the "fonts changed"
// invalidation reaches every node, SVG shapes included). As a CSS background a flag is ONE element, costs no node of its own, no request
// (the image is in the stylesheet), and paints on the first frame. They are not emoji: Windows ships no flag glyphs, so an emoji flag shows
// up there as two letters. Same on every system, in the palette (platin where a flag is white, obsidian-graphite where it is black, never
// #fff or #000), simplified at 20 x 14 px: a coat of arms or a crest would only be noise at that size. Decorative: the language or the
// market is always named in text beside it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'app', 'flags.css');

const RED = '#b0353f';
const PLATIN = '#dcdce0';
const GRAPHITE = '#202024';
const GOLD = '#d6aa3c';

const n = (value) => String(Math.round(value * 100) / 100);

/** A regular five-pointed star as a polygon: outer radius r, pointing at `rotate` degrees (0 = straight up). */
function star(cx, cy, r, rotate = 0) {
  const points = [];
  for (let i = 0; i < 10; i++) {
    const radius = i % 2 === 0 ? r : r * 0.382;
    const angle = ((rotate + i * 36 - 90) * Math.PI) / 180;
    points.push(`${n(cx + radius * Math.cos(angle))},${n(cy + radius * Math.sin(angle))}`);
  }
  return points.join(' ');
}

const rect = (attrs, fill) => `<rect ${attrs} fill='${fill}'/>`;
const circle = (cx, cy, r, fill) => `<circle cx='${cx}' cy='${cy}' r='${r}' fill='${fill}'/>`;
const polygon = (points, fill) => `<polygon points='${points}' fill='${fill}'/>`;

const stripes = [0, 4, 8, 12].map((y) => rect(`y='${y}' width='20' height='2'`, '#a83a46')).join('');
const stars = [0, 1, 2].flatMap((row) => [0, 1, 2, 3].map((col) => circle(n(1.6 + col * 2), n(1.5 + row * 2.4), 0.42, PLATIN))).join('');

/** Keyed by the FlagCode of i18n/routing.ts. */
const FLAGS = {
  us: rect("width='20' height='14'", PLATIN) + stripes + rect("width='9' height='8'", '#2e4373') + stars,
  tr: rect("width='20' height='14'", RED) + circle(7.3, 7, 3.5, PLATIN) + circle(8.4, 7, 2.8, RED) + polygon(star(11.4, 7, 1.9, -90), PLATIN),
  ae: rect("width='20' height='14'", PLATIN) + rect("x='5' width='15' height='4.67'", '#1f7a4d') + rect("x='5' y='9.33' width='15' height='4.67'", GRAPHITE) + rect("width='5' height='14'", RED),
  de: rect("width='20' height='14'", GRAPHITE) + rect("y='4.67' width='20' height='4.67'", '#b42b34') + rect("y='9.33' width='20' height='4.67'", GOLD),
  fr: rect("width='20' height='14'", PLATIN) + rect("width='6.67' height='14'", '#2f4c9a') + rect("x='13.33' width='6.67' height='14'", '#b8323e'),
  es: rect("width='20' height='14'", '#a93a44') + rect("y='3.5' width='20' height='7'", GOLD) + rect("x='4.2' y='4.7' width='2.6' height='4.6' rx='0.7'", '#8b3a3a'),
  cn:
    rect("width='20' height='14'", '#b43030') +
    polygon(star(4.2, 4.3, 2.5), '#e6c246') +
    polygon(star(8.5, 1.8, 0.85, 30), '#e6c246') +
    polygon(star(9.9, 3.7, 0.85, 10), '#e6c246') +
    polygon(star(9.9, 5.9, 0.85, -10), '#e6c246') +
    polygon(star(8.5, 7.7, 0.85, -30), '#e6c246'),
  jp: rect("width='20' height='14'", PLATIN) + circle(10, 7, 3.6, RED),
};

/** The characters a data URI in a quoted url() must not carry raw. */
const encode = (svg) => svg.replace(/[<>#%]/g, (c) => ({ '<': '%3C', '>': '%3E', '#': '%23', '%': '%25' })[c]);

const rules = Object.entries(FLAGS)
  .map(([code, art]) => `  .flag[data-flag='${code}'] {\n    background-image: url("data:image/svg+xml,${encode(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 20 14'>${art}</svg>`)}");\n  }`)
  .join('\n');

const css = `/* GENERATED by scripts/build-flags.mjs, do not edit by hand (npm run flags:build). Micro flags as CSS backgrounds: see that file for why. */
@layer components {
${rules}
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // Missing counts as different.
  }
  if (current !== css) {
    console.error('app/flags.css is not what scripts/build-flags.mjs draws. Run: npm run flags:build');
    process.exit(1);
  }
  console.log(`app/flags.css is in sync (${Object.keys(FLAGS).length} flags, ${css.length} bytes)`);
} else {
  writeFileSync(target, css);
  console.log(`wrote app/flags.css (${Object.keys(FLAGS).length} flags, ${css.length} bytes)`);
}
